/**
 * 扫一段话，返回命中的类别（同一类只回一条，带命中的具体模式名）。
 * 纯函数、无副作用，方便单测；文本先截断，避免超长消息把正则跑出病态开销。
 * @param {string} text
 * @returns {Array<{id:string,label:string,names:string[]}>}
 */
export function detectManipulation(text) {
  const t = String(text ?? '').slice(0, 2000)
  if (!t.trim()) return []
  const hits = []
  for (const group of PATTERN_GROUPS) {
    const names = group.patterns.filter((p) => p.re.test(t)).map((p) => p.name)
    if (names.length) hits.push({ id: group.id, label: group.label, names })
  }
  return hits
}

/**
 * 这一轮是不是主人。与 relationship 的 `isMasterTurn` 同一口径（两边都只读事件，不写状态）：
 *   · `sender.isMaster === true`（群聊/私聊都由 normalizeEvent + gate-wake 填好）；
 *   · 或者 chatKey 就是 `private:<adminQq>`（sender.isMaster 缺失时的兜底，也是硬门用的判据）。
 * @param {object} ev
 * @param {number|string} adminQq
 */
export function isMasterTurn(ev, adminQq = 0) {
  if (!ev) return false
  if (ev.sender?.isMaster === true) return true
  return Number(adminQq) > 0 && isMasterPrivate(ev.chatKey, adminQq)
}

/**
 * 这一轮该不该套"防攻略"软层：是真实的外人发言才套。
 * 排除：未唤醒 / 已被拦 / 戳一戳等 notice / 主动接话（sender.qq=0）/ 系统合成事件。
 * @param {object} ev
 * @param {number|string} adminQq
 */
export function isShieldTurn(ev, adminQq = 0) {
  if (!ev || ev.stopped || !ev.wake) return false
  if (ev._scratch?.notice) return false
  if (ev.wake.kind === 'proactive') return false
  // 入群欢迎是系统通知，不是新人在跟她说话；这时候套"外人硬约束"会让她把欢迎语说得像防贼。
  if (ev.wake.kind === 'welcome') return false
  const qq = Number(ev.sender?.qq)
  if (!Number.isInteger(qq) || qq <= 0) return false
  return !isMasterTurn(ev, adminQq)
}

